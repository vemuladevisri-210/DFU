from reportlab.lib.styles import getSampleStyleSheet
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer
from reportlab.lib.enums import TA_CENTER
from reportlab.lib.colors import darkblue, red, green
from reportlab.pdfbase import pdfmetrics
import os


def generate_report(
    patient_name,
    prediction,
    confidence,
    severity,
    healing_stage,
    wound_area,
    recommendations
):

    pdf_path = "DFU_Report.pdf"

    doc = SimpleDocTemplate(pdf_path)

    styles = getSampleStyleSheet()

    title_style = styles["Heading1"]
    title_style.alignment = TA_CENTER
    title_style.textColor = darkblue

    heading = styles["Heading2"]

    normal = styles["BodyText"]

    story = []

    # ==========================
    # Title
    # ==========================

    story.append(Paragraph("Diabetic Foot Ulcer Detection Report", title_style))
    story.append(Spacer(1, 20))

    # ==========================
    # Patient Information
    # ==========================

    story.append(Paragraph("<b>Patient Information</b>", heading))
    story.append(Paragraph(f"Patient Name : {patient_name}", normal))
    story.append(Spacer(1, 15))

    # ==========================
    # AI Prediction
    # ==========================

    story.append(Paragraph("<b>AI Prediction Result</b>", heading))

    color = green if prediction == "Healthy" else red

    prediction_style = styles["BodyText"]
    prediction_style.textColor = color

    story.append(
        Paragraph(f"<b>Prediction :</b> {prediction}", prediction_style)
    )

    story.append(
        Paragraph(f"<b>Confidence :</b> {confidence:.2f}%", normal)
    )

    story.append(
        Paragraph(f"<b>Severity :</b> {severity}", normal)
    )

    story.append(
        Paragraph(f"<b>Healing Stage :</b> {healing_stage}", normal)
    )

    story.append(
        Paragraph(f"<b>Estimated Wound Area :</b> {wound_area}%", normal)
    )

    story.append(Spacer(1, 20))

    # ==========================
    # Recommendations
    # ==========================

    story.append(Paragraph("<b>Medical Recommendations</b>", heading))

    for item in recommendations:
        story.append(Paragraph(f"• {item}", normal))

    story.append(Spacer(1, 20))

    # ==========================
    # Disclaimer
    # ==========================

    story.append(Paragraph("<b>Disclaimer</b>", heading))

    story.append(
        Paragraph(
            "This report is generated by an AI-based Diabetic Foot Ulcer Detection System. "
            "It is intended only as a clinical decision support tool and should not replace "
            "professional medical diagnosis or treatment.",
            normal
        )
    )

    story.append(Spacer(1, 20))

    # ==========================
    # Footer
    # ==========================

    story.append(
        Paragraph(
            "<b>Generated by AI-Powered Diabetic Foot Ulcer Detection System</b>",
            normal
        )
    )

    doc.build(story)

    return pdf_path